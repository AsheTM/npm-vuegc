import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";

const require = createRequire(import.meta.url);
const { vuegc } = require("../vuegc.js");
const { createVueProject, removeFolder, runVuegc, readComponent } = require("./support/vue-project.js");

const HINT = "Pug templates need the pug package: npm install -D pug";

describe("vuegc --template", () => {
    let project;

    beforeEach(() => { project = createVueProject(); });
    afterEach(() => { removeFolder(project); });

    it("writes the template in Pug with --template pug", () => {
        const { status } = runVuegc(project, ["--name", "Card", "--template", "pug"]);

        expect(status).toBe(0);
        expect(readComponent(project, "Card.vue")).toContain('<template lang="pug">\n    #Card Component #[span Card] generated by #[a(href="") VueGC]\n</template>\n');
    });

    it.each([
        { label: "--blank",     args: ["--blank"],  root: "div" },
        { label: "--module",    args: ["--module"], root: 'div(:class="$style.root") Component #[span Card] generated by #[a(href="") VueGC]' },
    ])("keeps the Pug template's content with $label", ({ args, root }) => {
        runVuegc(project, ["--name", "Card", "--template", "pug", ...args]);

        expect(readComponent(project, "Card.vue")).toContain(`<template lang="pug">\n    ${ root }\n</template>\n`);
    });

    it("generates the same component with --template html as without it", () => {
        runVuegc(project, ["--name", "Default"]);
        runVuegc(project, ["--name", "Default", "--template", "html", "--path", "html"]);

        expect(readComponent(project, "html/Default.vue")).toBe(readComponent(project, "Default.vue"));
        expect(readComponent(project, "Default.vue")).toMatch(/^<template>\n/);
    });

    it.each([
        { label: "an unsupported language",     args: ["--template", "jade"],               message: "Template jade not supported, use one of: html, pug" },
        { label: "--template without a value", args: ["--template"],                        message: "Template true not supported, use one of: html, pug" },
        { label: "--no-template",               args: ["--template", "pug", "--no-template"], message: "--template needs the template section: remove --no-template" },
    ])("refuses $label and writes nothing", ({ args, message }) => {
        const { status, stdout } = runVuegc(project, ["--name", "Card", ...args]);

        expect(status).toBe(1);
        expect(stdout).toContain(message);
        expect(readComponent(project, "Card.vue")).toBeNull();
    });

    // The hint compares with the project's package.json: it only shows when it can tell pug is missing
    it.each([
        { label: "without pug in package.json",    pkg: { devDependencies: { vite: "^7.0.0" } },  hint: true },
        { label: "with pug in devDependencies",     pkg: { devDependencies: { pug: "^3.0.3" } },   hint: false },
        { label: "with pug in dependencies",        pkg: { dependencies: { pug: "^3.0.3" } },      hint: false },
        { label: "without package.json",            pkg: null,                                      hint: false },
    ])("hints to install pug $label", ({ pkg, hint }) => {
        if(pkg)
            fs.writeFileSync(path.join(project, "package.json"), JSON.stringify(pkg));
        const { status, stdout } = runVuegc(project, ["--name", "Card", "--template", "pug"]);

        expect(status).toBe(0);
        expect(stdout.includes(HINT)).toBe(hint);
    });

    it("doesn't hint about pug for an HTML template", () => {
        fs.writeFileSync(path.join(project, "package.json"), JSON.stringify({ devDependencies: {} }));

        expect(runVuegc(project, ["--name", "Card"]).stdout).not.toContain("pug");
    });
});

describe("vuegc({ template })", () => {
    let project;

    beforeEach(() => {
        project = createVueProject();
        vi.spyOn(console, "log").mockImplementation(() => {});
    });
    afterEach(() => {
        removeFolder(project);
        vi.restoreAllMocks();
    });

    it.each([
        { label: "pug",                 options: {} },
        { label: "pug, blank",          options: { blank: true } },
        { label: "pug, module, scss",   options: { cssModule: true, style: "scss" } },
    ])("matches the snapshot: $label", ({ options }) => {
        const file = vuegc({ name: "Card", template: "pug", cwd: project, ...options });

        expect(fs.readFileSync(file, "utf-8")).toMatchSnapshot();
    });

    it("throws errno 0x000D for an unsupported language", () => {
        expect(() => vuegc({ name: "Card", template: "jade", cwd: project })).toThrow(expect.objectContaining({ errno: 0x000D, template: "jade" }));
    });

    it("throws errno 0x000E for Pug without the template section", () => {
        expect(() => vuegc({ name: "Card", template: "pug", noTemplate: true, cwd: project })).toThrow(expect.objectContaining({ errno: 0x000E }));
    });
});
