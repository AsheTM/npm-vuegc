import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { vuegc } = require("../vuegc.js");
const { createVueProject, removeFolder, runVuegc, readComponent } = require("./support/vue-project.js");

describe("vuegc --blank", () => {
    let project;

    beforeEach(() => { project = createVueProject(); });
    afterEach(() => { removeFolder(project); });

    it.each([
        { label: "--blank",         args: ["--blank"] },
        { label: "--blank true",    args: ["--blank", "true"] },
    ])("$label generates an empty template and style", ({ args }) => {
        const { status } = runVuegc(project, ["--name", "Hello", ...args]);
        const component = readComponent(project, "Hello.vue");

        expect(status).toBe(0);
        expect(component).toMatch(/<template>\s*<div><\/div>\s*<\/template>/);
        expect(component).toMatch(/<style lang="css" scoped>\r?\n<\/style>/);
        expect(component).not.toMatch(/generated by/);
        expect(component).not.toMatch(/font-size/);
    });

    it("keeps the script skeleton", () => {
        runVuegc(project, ["--name", "Hello", "--blank"]);
        const component = readComponent(project, "Hello.vue");

        expect(component).toMatch(/name: "Hello"/);
        expect(component).toMatch(/data\(\) \{\s*return \{ \};\s*\}/);
        expect(component).toMatch(/methods: \{ \}/);
    });

    it("works with the other flags", () => {
        runVuegc(project, ["--name", "Hello", "--blank", "--style", "css", "--scoped", "false"]);

        expect(readComponent(project, "Hello.vue")).toMatch(/<style lang="css">\r?\n<\/style>/);
    });

    it.each([
        { label: "(default)",       args: [] },
        { label: "--blank false",   args: ["--blank", "false"] },
    ])("$label keeps the demo content", ({ args }) => {
        runVuegc(project, ["--name", "Hello", ...args]);

        expect(readComponent(project, "Hello.vue")).toMatch(/generated by <a href="">VueGC<\/a>/);
    });
});

describe("vuegc({ blank })", () => {
    let project;

    beforeEach(() => {
        project = createVueProject();
        vi.spyOn(console, "log").mockImplementation(() => {});
    });
    afterEach(() => {
        removeFolder(project);
        vi.restoreAllMocks();
    });

    it("generates an empty template with blank: true", () => {
        vuegc({ name: "Hello", blank: true, cwd: project });

        expect(readComponent(project, "Hello.vue")).toMatch(/<div><\/div>/);
    });

    it("doesn't leak blank into the next component", () => {
        vuegc({ name: "First", blank: true, cwd: project });
        vuegc({ name: "Second", cwd: project });

        expect(readComponent(project, "Second.vue")).toMatch(/generated by/);
    });
});
