/**
 *  @description    Get value of a flag
 */
function getValueof(args, flag, obj = Object) {
    let thatValue   = null,  
        match       = false;
    args.forEach(value => {
        if(match)
            thatValue = value.startsWith("--") || value.startsWith("-") || value;
        match = (value == flag);
    });
    // Flag passed as last argument
    if(match)
        thatValue = true;
    return thatValue;
}
