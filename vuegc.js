//////////////////Error Handler/////////////////
////////////////////////////////////////////////
/**
 *  @description    Error handling
 */
function errorHandler(err) {
    let exit = err.exit;
    // System errors have a portable code, ours only an errno
    switch(err.code || err.errno) {
        case "EEXIST":
            console.log("\t[!] Component already exists [!]");
            exit = true;
            break;
        case "ENOENT":
            console.log("\t[!] It is not the root of Vue project [!]");
            exit = true;
            break;
        case 0x0001: 
            console.log("\t[!] main.js of Vue Project not found [!]");
            exit = true;
            break;
        case 0x0002: 
            console.log("\t[!] App.vue of Vue Project not found [!]");
            exit = true;
            break;
        case 0x0003: 
            console.log(`\t[!] Flag ${ err.flag } required [!]`);
            exit = true;
            break;
        case 0x0004:
            console.log(`\t[!] Style ${ err.style } not supported, use one of: ${ supported.style.join(", ") } [!]`);
            exit = true;
            break;
        default: 
            console.error(err);
            exit = true;
            break;
    }
    // If error spotted
    if(exit) {
        console.log("> Generating vue component failure");
        process.exit(1);
    }
}
