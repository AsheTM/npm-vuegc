/**
 *  @description    Prepare HandleBars for appending Template, Style and Script html content
 */
function registerHelpers(name, style, blank) {
    const componentFileName = toCapitalize(name.replace(/\.vue$/, ""));
    _registerHelperTemplate(componentFileName, blank);
    _registerHelperScript(componentFileName);
    _registerHelperStyle(componentFileName, style, blank);
}
function _registerHelperTemplate(componentFileName, blank) {
    Handlebars.registerHelper("defaultTemplate", function(text, url) {
        let result = blank
            ? `<div></div>`
            : `<div id="${ componentFileName }"> Component <span>${ componentFileName }</span> generated by <a href="">VueGC</a> </div>`;
        return new Handlebars.SafeString(result);
    });
}
function _registerHelperScript(componentFileName) {
    Handlebars.registerHelper("defaultScript", function(text, url) {
        let result = `export default {
    name: "${ componentFileName }",
    props: { },
    data() {
        return { };
    },
    methods: { }
}`;
        return new Handlebars.SafeString(result);
    });
}
function _registerHelperStyle(componentFileName, style, blank) {
    Handlebars.registerHelper("defaultStyle", function(text, url) {
        if(blank)
            return "";
        const spanStyle = "span { font-weight: bold; }";
        const aStyle = "a { font-style: italic; }";
        // Pre-processors support nesting, plain CSS gets the rules after the block
        const nested = style != "css";
        let result = `#${ componentFileName } {
    font-size: 16px;
    line-height: 150%;${ nested ? "\n\n    " + spanStyle + "\n    " + aStyle : "" }
}${ nested ? "" : "\n" + spanStyle + "\n" + aStyle }`;
        return new Handlebars.SafeString(result);
    }); 
}
